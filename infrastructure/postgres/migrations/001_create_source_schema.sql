-- Logical source relationships are validated during the seed transaction rather
-- than enforced as physical foreign keys. This preserves the ability to create
-- deterministic late-parent fixtures for downstream DEFERRED routing tests.
-- TODO(phase-0): Add the fixture generator before introducing mutable batches.

SELECT format(
    'CREATE ROLE %I LOGIN PASSWORD %L NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION',
    :'source_loader_user',
    :'source_loader_password'
)
WHERE NOT EXISTS (
    SELECT 1 FROM pg_roles WHERE rolname = :'source_loader_user'
)
\gexec

SELECT format(
    'ALTER ROLE %I WITH LOGIN PASSWORD %L NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION',
    :'source_loader_user',
    :'source_loader_password'
)
\gexec

SELECT format(
    'CREATE ROLE %I LOGIN PASSWORD %L NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION',
    :'source_reader_user',
    :'source_reader_password'
)
WHERE NOT EXISTS (
    SELECT 1 FROM pg_roles WHERE rolname = :'source_reader_user'
)
\gexec

SELECT format(
    'ALTER ROLE %I WITH LOGIN PASSWORD %L NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION',
    :'source_reader_user',
    :'source_reader_password'
)
\gexec

GRANT CONNECT ON DATABASE :"database_name" TO :"source_loader_user";
GRANT CONNECT ON DATABASE :"database_name" TO :"source_reader_user";

GRANT USAGE ON SCHEMA olist TO :"source_loader_user";
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA olist
    TO :"source_loader_user";
GRANT USAGE, SELECT, UPDATE ON ALL SEQUENCES IN SCHEMA olist
    TO :"source_loader_user";
GRANT USAGE ON SCHEMA audit TO :"source_loader_user";
GRANT SELECT, INSERT ON audit.source_seed_runs TO :"source_loader_user";

GRANT USAGE ON SCHEMA olist TO :"source_reader_user";
GRANT SELECT ON ALL TABLES IN SCHEMA olist TO :"source_reader_user";
GRANT USAGE ON SCHEMA audit TO :"source_reader_user";
GRANT SELECT ON audit.source_seed_runs TO :"source_reader_user";

ALTER DEFAULT PRIVILEGES IN SCHEMA olist
    GRANT SELECT, INSERT, UPDATE ON TABLES TO :"source_loader_user";
ALTER DEFAULT PRIVILEGES IN SCHEMA olist
    GRANT USAGE, SELECT, UPDATE ON SEQUENCES TO :"source_loader_user";
ALTER DEFAULT PRIVILEGES IN SCHEMA olist
    GRANT SELECT ON TABLES TO :"source_reader_user";
