-- Source database schema for the immutable Olist v1 snapshot and simulator state.
-- This file is executed by run_migrations.sh inside one transaction.

CREATE SCHEMA IF NOT EXISTS audit;
CREATE SCHEMA IF NOT EXISTS olist;

REVOKE ALL ON SCHEMA audit FROM PUBLIC;
REVOKE ALL ON SCHEMA olist FROM PUBLIC;

CREATE TABLE IF NOT EXISTS audit.schema_migrations (
    version text PRIMARY KEY,
    filename text NOT NULL UNIQUE,
    checksum char(64) NOT NULL,
    applied_at timestamp with time zone NOT NULL DEFAULT clock_timestamp(),
    applied_by text NOT NULL DEFAULT current_user
);

CREATE TABLE IF NOT EXISTS audit.source_seed_runs (
    snapshot_id text PRIMARY KEY,
    manifest_sha256 char(64) NOT NULL,
    seed_batch_id text NOT NULL,
    seed_source_updated_at timestamp with time zone NOT NULL,
    row_counts jsonb NOT NULL,
    status text NOT NULL,
    loaded_at timestamp with time zone NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT source_seed_runs_manifest_sha256_format
        CHECK (manifest_sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT source_seed_runs_status_values
        CHECK (status IN ('SUCCESS'))
);

CREATE TABLE IF NOT EXISTS olist.customers (
    customer_id text PRIMARY KEY,
    customer_unique_id text NOT NULL,
    customer_zip_code_prefix text NOT NULL,
    customer_city text NOT NULL,
    customer_state text NOT NULL,
    source_updated_at timestamp with time zone NOT NULL,
    source_sequence bigint GENERATED BY DEFAULT AS IDENTITY,
    source_operation text NOT NULL,
    source_batch_id text NOT NULL,
    source_loaded_at timestamp with time zone NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT customers_source_sequence_unique UNIQUE (source_sequence),
    CONSTRAINT customers_source_operation_values
        CHECK (source_operation IN ('INSERT', 'UPDATE'))
);

CREATE TABLE IF NOT EXISTS olist.geolocation (
