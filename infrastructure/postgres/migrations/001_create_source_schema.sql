    source_batch_id text NOT NULL,
    source_loaded_at timestamp with time zone NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT order_items_primary_key PRIMARY KEY (order_id, order_item_id),
    CONSTRAINT order_items_source_sequence_unique UNIQUE (source_sequence),
